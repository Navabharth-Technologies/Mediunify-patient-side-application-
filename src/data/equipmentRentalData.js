export const getEquipmentStatusStageIndex = (status) => {
  switch (status) {
    case 'Request Sent':
    case 'Request Received':
      return 0;
    case 'Availability Checking':
    case 'Equipment Available':
      return 1;
    case 'Rental Confirmed':
      return 2;
    case 'Preparing':
    case 'Preparing for Delivery':
      return 3;
    case 'Out for Delivery':
      return 4;
    case 'Delivered':
    case 'Active Rental':
      return 5;
    case 'Return Pending':
    case 'Return Scheduled':
      return 6;
    case 'Returned':
    case 'Equipment Returned':
    case 'Rental Completed':
      return 7;
    case 'Equipment Unavailable':
    case 'Cancelled':
      return -1;
    default:
      return 0;
  }
};

