// Helper to find lab by ID
export const getLabById = (labId) => {
  return radiologyLabs.find((lab) => lab.id === labId) || radiologyLabs[0];
};

// Helper to get all available tests across all labs
export const getAllRadiologyTests = () => {
  const tests = [];
  radiologyLabs.forEach((lab) => {
    lab.availableTests.forEach((test) => {
      tests.push({
        ...test,
        labId: lab.id,
        labName: lab.name,
        labArea: lab.area,
        labRating: lab.rating,
        labAccreditation: lab.accreditation,
        labDistance: lab.distance,
      });
    });
  });
  return tests;
};
