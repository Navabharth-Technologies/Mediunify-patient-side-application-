export const getNursingStageIndex = (status) => {
  if (!status) return 0;
  const s = status.toLowerCase();
  if (s.includes('not confirmed') || s.includes('rejected')) return 2; // Step 2 error state
  if (s.includes('service completed') || s.includes('completed') || s.includes('concluded')) return 3;
  if (s.includes('booking confirmed') || s.includes('confirmed') || s.includes('in progress') || s.includes('assigned')) return 2;
  if (s.includes('payment done') || s.includes('paid')) return 1;
  if (s.includes('payment pending') || s.includes('payment link')) return 0.5; // Pending payment
  if (s.includes('sent') || s.includes('submit') || s.includes('contacting') || s.includes('enquiry') || s.includes('call you')) return 0;
  return 0;
};

