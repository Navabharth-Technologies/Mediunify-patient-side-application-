/**
 * Normalizes user-selected or GPS-detected city names to canonical MediUnify pharmacy cities.
 */
export const normalizePharmacyCity = (rawCity) => {
  if (!rawCity || typeof rawCity !== 'string') return 'Mysuru';
  const clean = rawCity.trim().toLowerCase();

  if (clean.includes('hassan')) return 'Hassan';
  if (clean.includes('bengaluru') || clean.includes('bangalore')) return 'Bengaluru';
  if (clean.includes('mysuru') || clean.includes('mysore')) return 'Mysuru';
  if (clean.includes('mangaluru') || clean.includes('mangalore')) return 'Mangaluru';
  if (clean.includes('hubli') || clean.includes('hubballi')) return 'Hubballi';
  if (clean.includes('belagavi') || clean.includes('belgaum')) return 'Belagavi';

  // Capitalized return or fallback to Mysuru
  return rawCity.trim().charAt(0).toUpperCase() + rawCity.trim().slice(1);
};

/**
 * Resolves the active partner pharmacy store for a given city.
 */
export const getPharmacyStoreForCity = (cityStr) => {
  const norm = normalizePharmacyCity(cityStr);
  if (PHARMACY_STORES_BY_CITY[norm]) {
    return PHARMACY_STORES_BY_CITY[norm].partnerStore;
  }
  return PHARMACY_STORES_BY_CITY.Mysuru.partnerStore;
};

/**
 * Resolves full pharmacy configuration for a given city.
 */
export const getPharmacyCityConfig = (cityStr) => {
  const norm = normalizePharmacyCity(cityStr);
  if (PHARMACY_STORES_BY_CITY[norm]) {
    return PHARMACY_STORES_BY_CITY[norm];
  }
  return PHARMACY_STORES_BY_CITY.Mysuru;
};

